"""질문이 어느 길로 갈지 정한다. (판단만 하고 실행은 하지 않는다)

질문마다 답이 있는 곳이 다르다.
  "SQLD 자료 추천해줘"   → 게시글 안
  "이번 달 인기 글"      → DB 통계
  "너는 뭐 하는 챗봇이야" → 챗봇 자신
  "오늘 날씨 어때"       → 아무 데도 없음

전부 벡터 검색으로 보내면 답을 못 찾는다. 그래서 먼저 길을 가른다.

왜 LLM이 아니라 규칙인가:
- 빠르고(0초) 공짜이고 항상 같은 결과가 나온다
- **Step 15의 LLM 라우팅과 비교할 기준선**이 된다.
  기준선이 없으면 "LLM으로 바꿔서 좋아졌다"를 숫자로 말할 수 없다
"""
import re
from typing import Literal

Route = Literal["block", "person", "about", "how", "keywords", "popular", "reject", "clarify", "search"]

# 위에서부터 먼저 맞는 길로 간다. 순서가 곧 우선순위다.
RULES: list[tuple[Route, str]] = [
    # --- 공격·정책 차단이 가장 먼저 ---------------------------------------
    # block과 person을 reject에 합치지 않는 이유 둘:
    #  1) 측정 - 라우팅 정확도를 볼 때 "주제 밖 질문"과 "공격"은 다른 실패 유형이다
    #  2) 응답 - 사람 추적은 공격이 아니라 **정책 질문**이라 대안을 같이 줘야 한다
    #
    # 주의: 이 패턴은 사용자가 **직접 친 공격**만 막는다. 게시글 본문에 숨어 들어온
    # 공격은 라우터가 보지 못하므로 generator.py의 프롬프트 규칙이 막는다.
    ("block",
     # 지시 무시 / 규칙 해제
     # 사이에 "모두/전부/싹" 같은 말이 끼므로 몇 글자 건너뛸 수 있게 둔다
     r"(이전|위의|앞의|기존|모든|원래|지금까지)\s*(의\s*)?(지시|명령|규칙|설정|프롬프트|제약|말)"
     r"[^.!?\n]{0,12}?(무시|잊어|잊고|잊은|해제|취소|무효|버려|버리)|"
     # 프롬프트 탈취
     r"(시스템\s*)?(프롬프트|지시문|시스템\s*메시지|내부\s*규칙)\w*\s*[은는을를이가]?"
     r"\s*(알려|보여|출력|말해|공개|뱉|적어|읊)|"
     r"system\s*prompt|ignore\s+(all|previous|above|prior)|disregard\s+(all|previous)|"
     # 역할 바꾸기 - "너는 해적이야" 류.
     # 의문사는 제외해야 한다("너는 뭐야?"는 about으로 가야 함)
     r"너[는은]\s*(?!뭐|무슨|어떤|무엇|누구|어디|왜|언제|어떻)[가-힣A-Za-z]{1,10}(이야|이다|야\b|다\b)|"
     # 조사를 생략하기도 한다("너 이제 고양이야"). 뒤에 의문사가 오면 질문이므로 제외.
     r"(이제부터|지금부터|앞으로)\s*너[는은]?|"
     r"너\s*[는은]?\s*(이제|지금부터|앞으로)(?!\s*(뭐|무슨|어떻|어디|어때|언제))|"
     r"\S+(인\s*척|처럼)\s*(말|행동|대답|답변|굴)|"
     # 활용형이 갈린다: 바꾸다 → 바꿔서/바꾸고, 잊다 → 잊어/잊고
     r"역할[^.!?\n]{0,6}?(바꾸|바꿔|잊|변경|무시|벗어)|"
     # 말투 바꾸기. 심각하진 않지만 실제로 뚫렸다 - "반말로 대답해줘"에 반말로 답했다
     r"반말로\s*(대답|답|말|해|얘기|이야기)|말투[^.!?\n]{0,6}?(바꾸|바꿔|변경)|"
     r"(존댓말|반말)[^.!?\n]{0,4}?(말고|대신|빼|하지\s*마)|"
     r"롤\s*플레이|roleplay|jailbreak|탈옥|DAN\s*모드"),

    # 사람 추적 - 홈 순위보드가 글은 줄 세워도 사람은 안 줄 세운다. 챗봇만 그 선을 넘으면 안 된다.
    # ("안 쓴 사람"이 같은 질문의 뒷면이다. 340명 교육과정에서 글 수가 성실도로 읽히면 곤란하다)
    ("person",
     r"(제일|가장|젤)\s*(글\s*)?(많이|적게|조금)\s*(쓴|올린|작성한|게시한)\s*"
     r"(사람|분|유저|회원|교육생|사람이\s*누구|누구)|"
     r"누가\s*(제일|가장|젤)\s*(많이|적게|글)|"
     r"(사람|유저|작성자|교육생|회원|작성자)\s*(별)?\s*(랭킹|순위)|"
     r"글\s*(개수|수)\s*(랭킹|순위|많은\s*사람)|"
     r"(안|적게)\s*(쓰|쓴|올린)\w*\s*사람"),

    # "어떻게 동작하나" - 자기소개와 묻는 게 다르다.
    # 사람들은 주어를 생략한다("추천 기준이 뭐야?"에는 '너'가 없다). 그래서 동사·명사로 잡는다.
    ("how", r"(추천|검색|선정|고르|찾)\w*\s*(기준|방식|원리|방법)|"
            r"(어떤|무슨)\s*기준|어떻게\s*(찾|고르|추천|골라|동작|작동|정해)|"
            r"왜\s*(이|그)\s*글|어떤\s*원리|정확해|잘\s*찾"),

    # 서비스 자신에 대한 질문 - 게시글에는 답이 없다
    ("about", r"너[는가]?\s*(뭐|무슨|어떤)|넌\s*뭐|무슨\s*(기능|일|서비스)|뭐\s*하는|"
              r"어떤\s*(기능|걸|것).*(해|제공|도와)|사용법|어떻게\s*(써|사용)|"
              r"(스칼라|skala)\s*허브[는가]?\s*(뭐|무슨|어떤)"),

    # 집계 - 세어야 알 수 있다. 벡터 검색으로는 구조적으로 불가능
    ("keywords", r"키워드|트렌드|많이\s*(올라|언급|나오)|자주\s*(올라|언급|나오)|요즘\s*(뜨는|핫)"),
    ("popular",  r"인기|반응\s*(많|높)|좋아요\s*많|가장\s*많이\s*(본|저장|읽)|탑\s*\d|top\s*\d|순위"),

    # 서비스 밖
    ("reject", r"날씨|기온|비\s*와|주식|환율|코인|로또|운세|번역해|코드\s*짜줘|"
               r"(파이썬|자바|자바스크립트)\s*(코드|문법)\s*(알려|설명)"),
]

# 되묻기 기준: 너무 짧고 주제를 알 수 있는 단어가 없을 때
# (목업 api/chat.js:56 의 규칙을 옮겨온 것)
SHORT_CHARS = 7
HAS_TOPIC = re.compile(
    r"[A-Za-z]{2,}|툴|학습|자격|취업|서비스|캠퍼스|맛집|면접|스터디|프로젝트|배포|오류|에러",
    re.I,
)
ASKING = re.compile(r"추천|찾아|알려|보여|글|자료")


def route(question: str) -> Route:
    """질문에 길 이름을 붙인다."""
    q = question.strip()

    for name, pattern in RULES:
        if re.search(pattern, q, re.I):
            return name

    # 짧은데 주제어도 없으면 되물어야 한다. "자료" 한 단어로는 뭘 찾는지 알 수 없다.
    if len(q.replace(" ", "")) <= SHORT_CHARS and ASKING.search(q) and not HAS_TOPIC.search(q):
        return "clarify"

    return "search"
